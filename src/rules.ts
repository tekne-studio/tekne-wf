// wf's rules, rendered from templates/ and the project's config. The block in AGENTS.md
// (templates/rules.md) says only what every agent needs at every turn; each role's rules
// (templates/agent.md, templates/orchestrator.md) print on demand, by `wf --skill`, for
// the checkout it runs in. Like kb's block, wf's lives between its own markers: wf rewrites
// only what is inside, so kb's block and the project's own section never move.
import { existsSync, lstatSync, readFileSync, readlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Resolved } from './config';
import { codeList, fill, template } from './template';

export const OPENER = '<!-- wf:rules · generated by wf gen -->';
const OPEN = /<!-- wf:rules[^>]*-->/;
const CLOSE = '<!-- /wf:rules -->';
const KB_CLOSE = '<!-- /kb:global -->';

export type Role = 'agent' | 'orchestrator';

/** Whether the project's agents file carries kb's block: wf's rules then name kb's commands. */
export function hasKb(root: string, c: Resolved): boolean {
	const file = join(root, c.agentsFile);
	return existsSync(file) && readFileSync(file, 'utf8').includes(KB_CLOSE);
}

/** The block for AGENTS.md: what every agent needs without asking, and the pointer to `wf --skill`. */
export function renderRules(c: Resolved): string {
	return fill(template('rules'), { integration: c.integration }).trim();
}

/**
 * One role's rules, as `wf --skill` prints them. With `kb`, its block beside wf's says what
 * a decision is and where each fact lives, so wf's names kb's commands and leaves the rest
 * to it.
 */
export function renderRole(role: Role, c: Resolved, o: { kb?: boolean } = {}): string {
	return fill(template(role), {
		integration: c.integration,
		basis: o.kb ? "`kb why`, the decisions, the docs, the person's earlier choices" : "the decisions, the docs, the person's earlier choices",
		record: o.kb
			? 'Record an answer that is a decision with `kb decision new`.'
			: 'Record a decision (where the project keeps them) only when the choice had a plausible alternative someone would propose again, and Rejected names it; without one, the why goes in a code comment or the topic doc; one choice per decision.',
		homes: o.kb ? 'in its home' : "in the project's records (the decisions, the roadmap, the open questions)",
		look: c.look ? ` (${codeList(c.look.keys)} in \`${c.look.file}\`)` : '',
		tools: o.kb ? 'wf or kb' : 'wf',
		find: o.kb ? 'found with `kb search` or `kb why`' : "found in the project's docs",
		cheap: codeList(c.gates.cheap),
		touched: c.gates.expensive.length ? ` and, of the expensive ones (${codeList(c.gates.expensive)}), only the test files you touched` : '',
		shipGates: shipGates(c),
		skip: skip(c)
	}).trim();
}

/**
 * The look before each spawn: the orchestrator commits a change itself only where the ship
 * would run the cheap gates alone, so the commit passes every gate a ship would give it.
 * With expensive gates and no docs-only paths, the ship runs every gate on every file.
 * Each variant names only examples it allows: a code comment is never a doc, and a label is
 * what a reader sees. The person works in the main checkout too, so the commit takes only
 * its own files.
 */
function skip(c: Resolved): string {
	if (c.gates.expensive.length && !c.docsOnly.length) return 'Every task goes by `bun wf spawn`, your own records too: the ship runs every gate on every file.';
	const what = c.gates.expensive.length
		? `(your records, such as a decision, a question, a roadmap or doc line) and touches only docs (${codeList(c.docsOnly)})`
		: '(your records, such as a decision, a question, a roadmap or doc line; a typo, a comment)';
	return `Before each spawn, one look: when the change has no behavior ${what}, commit it on \`${c.integration}\` yourself, staging only its files (the person works here too), after the cheap gates and with no ship running (\`bun wf status\`, your background commands); anything else goes by \`bun wf spawn\`.`;
}

/**
 * What `ship` runs, as the rules say it: in proportion to the diff when the config has
 * docs-only paths. The agent's bullet already names each gate, so this names none.
 */
function shipGates(c: Resolved): string {
	if (!c.docsOnly.length || !c.gates.expensive.length) return 'every gate';
	return `the cheap gates alone when every changed file is docs (${codeList(c.docsOnly)}), otherwise every gate`;
}

/**
 * `text` with the block in place: between the markers when they exist; otherwise right
 * after kb's block, or at the end.
 */
export function withBlock(text: string, block: string): string {
	const body = `${OPENER}\n${block}\n${CLOSE}`;
	const open = text.match(OPEN);
	const end = text.indexOf(CLOSE);
	if (open?.index !== undefined && end > open.index) return text.slice(0, open.index) + body + text.slice(end + CLOSE.length);
	const kb = text.indexOf(KB_CLOSE);
	if (kb >= 0) {
		const at = kb + KB_CLOSE.length;
		return `${text.slice(0, at)}\n\n${body}${text.slice(at)}`;
	}
	return `${text.trimEnd()}\n\n${body}\n`;
}

function isLinkTo(path: string, target: string): boolean {
	try {
		return lstatSync(path).isSymbolicLink() && readlinkSync(path) === target;
	} catch {
		return false;
	}
}

/** What is wrong with the block (and the CLAUDE.md link); `gen` rewrites the block itself and says so. */
export function rulesProblems(root: string, c: Resolved, mode: 'check' | 'gen'): { problems: string[]; written: boolean } {
	const problems: string[] = [];
	const file = join(root, c.agentsFile);
	if (!existsSync(file)) return { problems: [`${c.agentsFile} is missing: run \`bun wf init\``], written: false };
	const claude = join(root, 'CLAUDE.md');
	if (c.agentsFile === 'AGENTS.md' && !isLinkTo(claude, 'AGENTS.md'))
		problems.push(existsSync(claude) ? 'CLAUDE.md must be a symlink to AGENTS.md (ln -sf AGENTS.md CLAUDE.md)' : 'CLAUDE.md is missing: ln -s AGENTS.md CLAUDE.md');
	const text = readFileSync(file, 'utf8');
	const next = withBlock(text, renderRules(c));
	if (next === text) return { problems, written: false };
	if (mode === 'gen') {
		writeFileSync(file, next);
		return { problems, written: true };
	}
	problems.push(`the wf block in ${c.agentsFile} is ${OPEN.test(text) ? 'stale' : 'missing'}: run \`bun wf gen\``);
	return { problems, written: false };
}
